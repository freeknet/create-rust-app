// ============================================================================
// Module:       @@module@@
// Description:  Rebuild CHANGELOG.md from conventional commits and git tags.
//
// Dependencies: anyhow; std::fs and std::process
// ============================================================================

//! Generate Keep a Changelog sections from reachable vMAJOR.MINOR.PATCH tags.
//! Merge commits and commits touching only CHANGELOG.md are excluded.
//! `--check` compares released entries only: Unreleased changes on every commit.
//! Regeneration replaces the file, so release prose belongs in release notes.

use anyhow::{Context as _, Result, bail};
use std::process::Command;

const HEADINGS: &[&str] = &[
    "Breaking changes",
    "Added",
    "Fixed",
    "Performance",
    "Changed",
    "Documentation",
    "Tests",
    "Internal",
    "Other",
];

fn git(args: &[&str]) -> Result<String> {
    let output = Command::new("git")
        .args(args)
        .output()
        .context("could not start git")?;
    if !output.status.success() {
        bail!(
            "git {} failed: {}",
            args.join(" "),
            String::from_utf8_lossy(&output.stderr).trim()
        );
    }
    String::from_utf8(output.stdout).context("git output was not UTF-8")
}

fn version(tag: &str) -> Option<(u64, u64, u64)> {
    let mut parts = tag.strip_prefix('v')?.split('.');
    let result = (
        parts.next()?.parse().ok()?,
        parts.next()?.parse().ok()?,
        parts.next()?.parse().ok()?,
    );
    parts.next().is_none().then_some(result)
}

fn subject_parts(subject: &str) -> (&str, String) {
    let Some((head, summary)) = subject.split_once(':') else {
        return ("Other", subject.to_owned());
    };
    let breaking = head.ends_with('!');
    let head = head.strip_suffix('!').unwrap_or(head);
    let (kind, scope) = match head.split_once('(') {
        Some((kind, scope)) => match scope.strip_suffix(')') {
            Some(scope) if !scope.is_empty() => (kind, Some(scope)),
            _ => return ("Other", subject.to_owned()),
        },
        None => (head, None),
    };
    if kind.is_empty() || !kind.chars().all(|c| c.is_ascii_lowercase()) || summary.trim().is_empty()
    {
        return ("Other", subject.to_owned());
    }
    let heading = if breaking {
        "Breaking changes"
    } else {
        match kind {
            "feat" => "Added",
            "fix" => "Fixed",
            "perf" => "Performance",
            "refactor" | "style" => "Changed",
            "docs" => "Documentation",
            "test" => "Tests",
            "build" | "ci" | "chore" => "Internal",
            _ => "Other",
        }
    };
    let summary = match scope {
        Some(scope) => format!("**{scope}:** {}", summary.trim()),
        None => summary.trim().to_owned(),
    };
    (heading, summary)
}

fn push_commits(out: &mut String, range: &str) -> Result<()> {
    let log = git(&[
        "log",
        "--no-merges",
        "--full-history",
        "--format=%h%x1f%s",
        range,
        "--",
        ".",
        ":(exclude)CHANGELOG.md",
    ])?;
    let entries: Vec<_> = log
        .lines()
        .filter_map(|line| line.split_once('\u{1f}'))
        .map(|(hash, subject)| {
            let (heading, summary) = subject_parts(subject);
            (heading, format!("- {summary} (`{hash}`)\n"))
        })
        .collect();
    for heading in HEADINGS {
        let matching: Vec<_> = entries.iter().filter(|(h, _)| h == heading).collect();
        if !matching.is_empty() {
            out.push_str(&format!("\n### {heading}\n\n"));
            for (_, entry) in matching {
                out.push_str(entry);
            }
        }
    }
    if entries.is_empty() {
        out.push_str("\nNo changes recorded.\n");
    }
    Ok(())
}

fn released_only(text: &str) -> String {
    let mut skipping = false;
    text.lines()
        .filter(|line| {
            if line.starts_with("## [Unreleased]") {
                skipping = true;
            } else if line.starts_with("## [") {
                skipping = false;
            }
            !skipping
        })
        .collect::<Vec<_>>()
        .join("\n")
}

pub(crate) fn run(check: bool) -> Result<()> {
    // Fail before writing anything in an uninitialised repository.
    git(&["rev-parse", "--verify", "HEAD"])?;
    let tags = git(&["tag", "--merged", "HEAD", "--list", "v*"])?;
    let mut releases: Vec<_> = tags
        .lines()
        .filter_map(|tag| version(tag).map(|v| (v, tag)))
        .collect();
    releases.sort_by_key(|entry| std::cmp::Reverse(entry.0));
    let mut out = String::from(
        "# Changelog\n\n\
         All notable changes to @@name@@. Generated by `cargo xtask changelog`.\n\n\
         The format follows [Keep a Changelog](https://keepachangelog.com/en/1.1.0/)\n\
         and [Semantic Versioning](https://semver.org/spec/v2.0.0.html).\n\n\
         ## [Unreleased]\n",
    );
    let range = releases
        .first()
        .map_or_else(|| "HEAD".to_owned(), |(_, tag)| format!("{tag}..HEAD"));
    push_commits(&mut out, &range)?;
    for (index, (_, tag)) in releases.iter().enumerate() {
        let date = git(&["log", "-1", "--format=%cs", tag, "--"])?;
        out.push_str(&format!(
            "\n## [{}] - {}\n",
            tag.trim_start_matches('v'),
            date.trim()
        ));
        let range = releases
            .get(index + 1)
            .map_or_else(|| (*tag).to_owned(), |(_, prev)| format!("{prev}..{tag}"));
        push_commits(&mut out, &range)?;
    }
    if check {
        let existing = std::fs::read_to_string("CHANGELOG.md")
            .context("could not read CHANGELOG.md; run `cargo xtask changelog`")?;
        if released_only(&existing) != released_only(&out) {
            bail!("released changelog entries differ; run `cargo xtask changelog`");
        }
        println!("CHANGELOG.md matches the released history.");
    } else {
        std::fs::write("CHANGELOG.md", out).context("could not write CHANGELOG.md")?;
        println!("Wrote CHANGELOG.md.");
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::{released_only, subject_parts, version};

    #[test]
    fn conventional_subjects_keep_scope_and_breaking_markers() -> anyhow::Result<()> {
        assert_eq!(
            subject_parts("feat(ui)!: replace settings"),
            ("Breaking changes", "**ui:** replace settings".to_owned()),
            "breaking changes lead regardless of type"
        );
        for subject in ["fix(unclosed: broken", "Feat: title", "feat:", "plain text"] {
            assert_eq!(
                subject_parts(subject),
                ("Other", subject.to_owned()),
                "malformed subjects stay intact"
            );
        }
        assert_eq!(subject_parts("fix: repair").0, "Fixed", "fix mapping");
        Ok(())
    }

    #[test]
    fn versions_sort_numerically_and_reject_partial_tags() -> anyhow::Result<()> {
        assert!(version("v0.10.0") > version("v0.9.0"), "numeric order");
        for tag in ["v1.2", "v1.2.3.4", "v1.2.3-rc.1", "unrelated"] {
            assert_eq!(version(tag), None, "only stable version tags: {tag}");
        }
        Ok(())
    }

    #[test]
    fn check_ignores_unreleased_but_detects_release_drift() -> anyhow::Result<()> {
        let original = "# Changelog\n\n## [Unreleased]\nnew\n\n## [0.1.0]\nold\n";
        assert_eq!(
            released_only(original),
            released_only(&original.replace("new", "other")),
            "unreleased content changes with each commit"
        );
        assert_ne!(
            released_only(original),
            released_only(&original.replace("old", "drift")),
            "released entries must match history"
        );
        Ok(())
    }
}
